CREATE DATABASE IF NOT EXISTS fraud;

CREATE TABLE IF NOT EXISTS fraud.transactions_base
(
    row_id UInt64,
    transaction_time DateTime('UTC'),
    merch String,
    cat_id String,
    amount Decimal(18, 2),
    name_1 String,
    name_2 String,
    gender String,
    street String,
    one_city String,
    us_state String,
    post_code String,
    lat Float64,
    lon Float64,
    population_city UInt32,
    jobs String,
    merchant_lat Float64,
    merchant_lon Float64
)
ENGINE = MergeTree
ORDER BY row_id;
